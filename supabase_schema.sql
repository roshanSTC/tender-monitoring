-- 1. Create Tenders Table
CREATE TABLE IF NOT EXISTS public.tenders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    source_url TEXT,
    unit_name TEXT,
    tender_number TEXT NOT NULL,
    tender_title TEXT,
    matched_keyword TEXT DEFAULT '-',
    publishing_date TEXT,
    closing_date TEXT,
    status TEXT DEFAULT 'Active',
    days_left INTEGER,
    tender_document TEXT,
    tender_document_url TEXT,
    corrigendum TEXT,
    corrigendum_url TEXT,
    scraped_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    
    -- Prevent duplicate tenders from the same source
    CONSTRAINT uq_tender_source_number UNIQUE (source, tender_number)
);

-- 2. Performance Indexes
CREATE INDEX IF NOT EXISTS idx_tenders_source ON public.tenders (source);
CREATE INDEX IF NOT EXISTS idx_tenders_tender_number ON public.tenders (tender_number);
CREATE INDEX IF NOT EXISTS idx_tenders_status ON public.tenders (status);
CREATE INDEX IF NOT EXISTS idx_tenders_matched_keyword ON public.tenders (matched_keyword);
CREATE INDEX IF NOT EXISTS idx_tenders_created_at ON public.tenders (created_at DESC);

-- 3. Row Level Security (RLS) Configuration
-- Enable RLS for table security
ALTER TABLE public.tenders ENABLE ROW LEVEL SECURITY;

-- Allow read access to authenticated users and public (adjust as needed for your application)
CREATE POLICY "Allow public read access" 
ON public.tenders FOR SELECT 
USING (true);

-- Allow full access to service_role (backend scraper)
CREATE POLICY "Allow service role full access" 
ON public.tenders FOR ALL 
TO service_role 
USING (true) 
WITH CHECK (true);

-- Allow insert/update for authenticated or anon (if using anon key for the backend)
CREATE POLICY "Allow anon insert and update" 
ON public.tenders FOR ALL 
TO anon 
USING (true) 
WITH CHECK (true);

-- 4. Automatically update 'updated_at' timestamp on row update
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_tenders_updated_at ON public.tenders;
CREATE TRIGGER update_tenders_updated_at
BEFORE UPDATE ON public.tenders
FOR EACH ROW
EXECUTE FUNCTION update_updated_at_column();

